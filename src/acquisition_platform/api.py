@app.post("/match", response_model=MatchResult, tags=["engines"])
def match(request: MatchRequest) -> MatchResult:
    """Match buyers to sellers using the GAP solver."""
    buyers = [Buyer(id=b.id, budget=b.budget, preferences=b.preferences) for b in request.buyers]
    sellers = [Seller(id=s.id, asking_price=s.asking_price, attributes=s.attributes) for s in request.sellers]
    matcher = BuyerSellerMatcher()
    matches = matcher.match(buyers, sellers)
    return MatchResult(
        matches=[
            MatchResponse(
                buyer_id=m.buyer_id,
                seller_id=m.seller_id,
                score=m.score,
                confidence=m.confidence,
            )
            for m in matches
        ],
        count=len(matches),
    )


@app.post("/value", response_model=ValuationResponse, tags=["engines"])
def value(request: ValuationRequest) -> ValuationResponse:
    """Compute business valuation using the specified method."""
    engine = ValuationEngine()
    method = request.method

    if method == ValuationMethod.DCF:
        if request.free_cash_flow is None or request.growth_rate is None or request.discount_rate is None or request.terminal_growth is None or request.years is None:
            raise ValidationError("DCF requires free_cash_flow, growth_rate, discount_rate, terminal_growth, years")
        if request.discount_rate == request.terminal_growth:
            raise DivisionByZeroError("discount_rate and terminal_growth cannot be equal")
        result = engine.dcf_valuation(
            free_cash_flow=request.free_cash_flow,
            growth_rate=request.growth_rate,
            discount_rate=request.discount_rate,
            terminal_growth=request.terminal_growth,
            years=request.years,
        )
    elif method == ValuationMethod.COMPS:
        if request.metric is None or request.multiple is None:
            raise ValidationError("Comps requires metric and multiple")
        result = engine.comparable_valuation(metric=request.metric, multiple=request.multiple)
    elif method == ValuationMethod.SDE:
        if request.sde is None or request.multiple is None:
            raise ValidationError("SDE requires sde and multiple")
        result = engine.sde_valuation(sde=request.sde, multiple=request.multiple)
    elif method == ValuationMethod.ARR:
        if request.arr is None or request.multiple is None:
            raise ValidationError("ARR requires arr and multiple")
        result = engine.arr_valuation(arr=request.arr, multiple=request.multiple)
    elif method == ValuationMethod.ENSEMBLE:
        if request.free_cash_flow is None or request.revenue is None or request.growth_rate is None or request.discount_rate is None or request.terminal_growth is None or request.revenue_multiple is None or request.years is None:
            raise ValidationError("Ensemble requires free_cash_flow, revenue, growth_rate, discount_rate, terminal_growth, revenue_multiple, years")
        result = engine.ensemble_valuation(
            free_cash_flow=request.free_cash_flow,
            revenue=request.revenue,
            growth_rate=request.growth_rate,
            discount_rate=request.discount_rate,
            terminal_growth=request.terminal_growth,
            revenue_multiple=request.revenue_multiple,
            years=request.years,
        )
    else:
        raise ValidationError(f"Unknown valuation method: {method}")

    return ValuationResponse(
        value=result.value,
        method=result.method,
        confidence=result.confidence,
        low_estimate=result.low_estimate,
        high_estimate=result.high_estimate,
    )


@app.post("/fraud-check", response_model=FraudCheckResponse, tags=["engines"])
def fraud_check(request: FraudCheckRequest) -> FraudCheckResponse:
    """Detect fraud via signal scoring or graph analysis."""
    detector = FraudDetector()

    if request.signals is not None:
        if len(request.signals) == 0:
            return FraudCheckResponse(
                score=0.0,
                risk_level="low",
                confidence=0.0,
                explanations=["No signals provided"],
            )
        signals = [FraudSignal(name=s.name, value=s.value) for s in request.signals]
        result = detector.score(signals)
        return FraudCheckResponse(
            score=result.score,
            risk_level=result.risk_level,
            confidence=result.confidence,
            explanations=result.explanations,
        )

    if request.graph is not None:
        graph = {"nodes": request.graph.nodes, "edges": request.graph.edges}
        result = detector.analyze_graph(graph)
        return FraudCheckResponse(
            score=result.score,
            risk_level=result.risk_level,
            confidence=result.confidence,
            explanations=result.explanations,
            has_ring=result.has_ring,
            risk_score=result.risk_score,
        )

    raise ValidationError("Either signals or graph must be provided")


@app.post("/optimize", response_model=OptimizeResponse, tags=["engines"])
def optimize(request: OptimizeRequest) -> OptimizeResponse:
    """Optimize portfolio using greedy MIQP approximation."""
    assets = [
        Asset(id=a.id, cost=a.cost, expected_return=a.expected_return, risk=a.risk, sector=a.sector)
        for a in request.assets
    ]
    optimizer = PortfolioOptimizer(budget=request.budget, max_assets=request.max_assets)
    portfolio = optimizer.optimize(assets, risk_tolerance=request.risk_tolerance)
    return OptimizeResponse(
        assets=[
            AssetResponse(
                id=a.id,
                cost=a.cost,
                expected_return=a.expected_return,
                risk=a.risk,
                sector=a.sector,
            )
            for a in portfolio.assets
        ],
        expected_return=portfolio.expected_return,
        sharpe_ratio=portfolio.sharpe_ratio,
    )


