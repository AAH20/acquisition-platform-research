# In-memory metrics counters
_METRICS: dict[str, Any] = {
    "total_requests": 0,
    "total_errors": 0,
    "endpoints": {},
}


def _record_request(path: str, status_code: int) -> None:
    """Record a request in the metrics counters."""
    _METRICS["total_requests"] += 1
    ep = _METRICS["endpoints"].setdefault(
        path, {"requests": 0, "errors": 0}
    )
    ep["requests"] += 1
    if status_code >= 400:
        _METRICS["total_errors"] += 1
        ep["errors"] += 1


@app.middleware("http")
async def metrics_middleware(request: Request, call_next: Callable[..., Any]) -> Any:
    """Track request counts and error rates per endpoint."""
    response = await call_next(request)
    _record_request(request.url.path, response.status_code)
    return response


