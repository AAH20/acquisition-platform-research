@app.post("/resolve", response_model=ResolveResponse, tags=["engines"])
def resolve(request: ResolveRequest) -> ResolveResponse:
    """Resolve entities into clusters using blocking + Jaro-Winkler."""
    entities = [e.model_dump(exclude_none=True) for e in request.entities]
    resolver = EntityResolver(threshold=request.threshold)
    clusters = resolver.resolve(entities)
    return ResolveResponse(
        clusters=[
            EntityClusterResponse(
                entities=[dict(e) for e in c.entities],
                canonical_name=c.canonical_name,
            )
            for c in clusters
        ],
        count=len(clusters),
    )


