@app.post("/evolve", response_model=EvolveResponse, tags=["engines"])
def evolve(request: EvolveRequest) -> EvolveResponse:
    """Run genetic algorithm evolution for hyperparameter optimization."""
    engine = EvolutionEngine(
        population_size=request.population_size,
        generations=request.generations,
        mutation_rate=request.mutation_rate,
        elitism=request.elitism,
    )

    if request.fitness == FitnessFunction.QUADRATIC:
        fitness_fn = lambda gene: -((gene - 0.5) ** 2) + 1.0
    else:
        import math
        fitness_fn = lambda gene: math.sin(gene * math.pi)

    result = engine.evolve(fitness_fn, (request.gene_min, request.gene_max))
    return EvolveResponse(
        best_fitness=result.best_fitness,
        generation_count=result.generation_count,
        population_size=result.population_size,
        diversity=result.diversity,
        offspring_count=result.offspring_count,
        converged=result.converged,
        worst_fitness=result.worst_fitness,
    )


